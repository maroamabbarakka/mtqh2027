import { expect, test } from "@playwright/test";

test("admin kafilah mengajukan peserta dan verifikator meminta revisi", async ({ page }) => {
  await page.goto("/login");
  await page.getByLabel("Email", { exact: true }).fill("admin.tiroang@example.test");
  await page.getByLabel("Kata sandi", { exact: true }).fill("123456");
  await page.getByRole("button", { name: "Masuk dengan aman" }).click();
  await page.getByLabel("Kata sandi saat ini").fill("123456");
  await page.getByLabel("Kata sandi baru", { exact: true }).fill("KafilahTiroang-2027!");
  await page.getByLabel("Konfirmasi kata sandi baru").fill("KafilahTiroang-2027!");
  await page.getByRole("button", { name: "Perbarui kata sandi" }).click();
  await expect(page.getByText("Kata sandi berhasil diubah.")).toBeVisible();
  await page.goto("/app/peserta");
  await expect(page.getByRole("heading", { name: "Peserta & Regu" })).toBeVisible();
  await page.getByRole("button", { name: "Pendaftaran baru" }).click();
  await expect(page.getByLabel("Kecamatan")).toBeDisabled();
  await page.getByLabel("Golongan").selectOption("contoh-tilawah-putra");
  await page.getByRole("button", { name: "Lanjut" }).click();
  await page.getByLabel("Nama lengkap peserta").fill("Peserta Simulasi E2E");
  await page.getByLabel("Nama pengurus").fill("Pengurus Kafilah Tiroang");
  await page.getByLabel("Nomor pengurus").fill("081234567890");
  await page.getByRole("button", { name: "Lanjut" }).click();
  await page.getByText("Saya memastikan data").click();
  await page.screenshot({ path: "artifacts/screenshots/phase-05/registration-wizard-1440.png", fullPage: true });
  await page.getByRole("button", { name: "Simpan draft" }).click();
  await expect(page.getByText("Pendaftaran tersimpan sebagai draft")).toBeVisible();
  await expect(page.getByText("Peserta Simulasi E2E")).toBeVisible();
  await page.getByRole("button", { name: "Ajukan", exact: true }).click();
  await expect(page.getByText("Pendaftaran berhasil diajukan.")).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: "artifacts/screenshots/phase-06/registration-submitted-390.png", fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth)).toBe(false);

  await page.setViewportSize({ width: 1440, height: 900 });
  await page.getByRole("button", { name: "Keluar dari akun" }).click();
  await page.getByLabel("Email", { exact: true }).fill("verifikator@example.test");
  await page.getByLabel("Kata sandi", { exact: true }).fill("123456");
  await page.getByRole("button", { name: "Masuk dengan aman" }).click();
  await page.getByLabel("Kata sandi saat ini").fill("123456");
  await page.getByLabel("Kata sandi baru", { exact: true }).fill("Verifikator-2027!");
  await page.getByLabel("Konfirmasi kata sandi baru").fill("Verifikator-2027!");
  await page.getByRole("button", { name: "Perbarui kata sandi" }).click();
  await expect(page.getByText("Kata sandi berhasil diubah.")).toBeVisible();
  await page.goto("/app/peserta");
  await page.getByRole("button", { name: "Mulai review" }).click();
  await expect(page.getByText("Pemeriksaan dimulai.")).toBeVisible();
  await page.getByRole("button", { name: "Putuskan" }).click();
  await page.getByLabel("Alasan keputusan").fill("Mohon perbaiki nama resmi sesuai administrasi kafilah.");
  await page.screenshot({ path: "artifacts/screenshots/phase-06/review-decision-1440.png", fullPage: true });
  await page.getByRole("button", { name: "Minta revisi" }).click();
  await expect(page.getByText("Pendaftaran dikembalikan untuk revisi.")).toBeVisible();
  await expect(page.locator(".badge", { hasText: "Perlu revisi" })).toBeVisible();
});
